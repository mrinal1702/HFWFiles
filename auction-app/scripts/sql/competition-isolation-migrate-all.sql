-- ─── 12. Competition-aware upsert RPC (for future gameweeks) ────────────────
create or replace function public.upsert_player_scores_for_round(
  p_competition_round_id bigint,
  p_rows jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_upserted integer;
  v_legacy_gw bigint;
begin
  if p_competition_round_id is null then
    raise exception 'p_competition_round_id is required';
  end if;
  if p_rows is null or jsonb_typeof(p_rows) <> 'array' then
    raise exception 'p_rows must be a JSON array';
  end if;

  select legacy_game_week_id into v_legacy_gw
  from public.competition_rounds where id = p_competition_round_id;
  if v_legacy_gw is null then
    raise exception 'competition_round % has no legacy_game_week_id', p_competition_round_id;
  end if;

  insert into public."Player_Scores"
    (player_id, game_week_id, "Score", competition_round_id, competition_match_id, fotmob_match_id)
  select
    (r->>'player_id')::bigint,
    v_legacy_gw,
    (r->>'score')::numeric,
    p_competition_round_id,
    cm.id,
    (r->>'fotmob_match_id')::bigint
  from jsonb_array_elements(p_rows) as r
  left join public.competition_matches cm
    on cm.round_id = p_competition_round_id
   and cm.fotmob_match_id = (r->>'fotmob_match_id')::bigint
  where (r->>'player_id') is not null
    and (r->>'score') is not null
  on conflict (player_id, game_week_id)
  do update set
    "Score"              = excluded."Score",
    competition_round_id = excluded.competition_round_id,
    competition_match_id = excluded.competition_match_id,
    fotmob_match_id      = excluded.fotmob_match_id;

  get diagnostics v_upserted = row_count;
  return jsonb_build_object(
    'competition_round_id', p_competition_round_id,
    'legacy_game_week_id', v_legacy_gw,
    'upserted', v_upserted
  );
end;
$$;
grant execute on function public.upsert_player_scores_for_round(bigint, jsonb) to service_role;

-- ─── 13. Convenience view: scores joined to competition/round/match ─────────
create or replace view public.player_scores_scoped as
select
  ps.id,
  ps.player_id,
  ps."Score"              as score,
  ps.game_week_id,
  ps.competition_round_id,
  cr.round_slug,
  cr.competition_id,
  c.slug                  as competition_slug,
  ps.fotmob_match_id,
  cm.match_slug
from public."Player_Scores" ps
left join public.competition_rounds cr  on cr.id = ps.competition_round_id
left join public.competitions c         on c.id = cr.competition_id
left join public.competition_matches cm on cm.id = ps.competition_match_id;

