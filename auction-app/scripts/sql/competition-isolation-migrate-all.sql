-- ─── 1. Tables ──────────────────────────────────────────────────────────────
create table if not exists public.competitions (
  id           bigint generated by default as identity primary key,
  slug         text not null unique,
  name         text not null,
  status       text not null default 'active'
                 check (status in ('active', 'completed', 'archived')),
  archived_at  timestamptz,
  created_at   timestamptz not null default now()
);

create table if not exists public.competition_rounds (
  id                   bigint generated by default as identity primary key,
  competition_id       bigint not null references public.competitions(id) on delete cascade,
  round_slug           text   not null,
  display_name         text,
  round_number         integer,
  status               text   not null default 'open',
  is_active            boolean not null default false,
  legacy_game_week_id  bigint,
  created_at           timestamptz not null default now(),
  unique (competition_id, round_slug)
);
create index if not exists idx_competition_rounds_competition on public.competition_rounds (competition_id);
create index if not exists idx_competition_rounds_legacy_gw   on public.competition_rounds (legacy_game_week_id);

create table if not exists public.competition_matches (
  id               bigint generated by default as identity primary key,
  competition_id   bigint not null references public.competitions(id) on delete cascade,
  round_id         bigint not null references public.competition_rounds(id) on delete cascade,
  fotmob_match_id  bigint not null,
  match_slug       text,
  home_team        text,
  away_team        text,
  played_at        timestamptz,
  created_at       timestamptz not null default now(),
  unique (competition_id, fotmob_match_id)
);
create index if not exists idx_competition_matches_round on public.competition_matches (round_id);

create table if not exists public.competition_players (
  competition_id   bigint not null references public.competitions(id) on delete cascade,
  player_id        bigint not null,
  player_name      text,
  position         text,
  team_id          bigint,
  team_name        text,
  primary key (competition_id, player_id)
);

